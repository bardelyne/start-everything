import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const output=process.argv[2]||fs.mkdtempSync(path.join(os.tmpdir(),'start-shell-actions-'));fs.mkdirSync(output,{recursive:true});
const source=fs.readFileSync(path.join(root,'start-everything.wh.cpp'),'utf8');
const first=source.indexOf('namespace shellactions {'),last=source.indexOf('}  // namespace shellactions',first);
if(first<0||last<0)throw Error('Missing shell-action production boundaries');
const common=source.slice(source.indexOf('// <search-text>'),source.indexOf('// </search-text>'));
const code=fs.readFileSync(path.join(root,'tests/shell-actions.cpp'),'utf8').replace('// PRODUCTION_SHELL_ACTIONS',common+source.slice(first,last)+'}\n');
const cpp=path.join(output,'shell-actions.cpp'),exe=path.join(output,'shell-actions.exe');fs.writeFileSync(cpp,code);
const options={encoding:'utf8',windowsHide:true,timeout:120000,env:{...process.env,TEMP:output,TMP:output}};
const compiler=process.env.CXX||'C:/Program Files/Windhawk/Compiler/bin/clang++.exe';
const build=spawnSync(compiler,['--target=x86_64-w64-mingw32','-std=c++23','-O2','-static',cpp,'-o',exe,'-lole32','-loleaut32','-lshell32','-luuid','-lruntimeobject'],options);
if(build.status!==0)throw Error((build.stdout||'')+(build.stderr||String(build.error||'')));
const result=spawnSync(exe,process.argv.includes('--live')?['--live']:[],options);
const log=(result.stdout||'')+(result.stderr||String(result.error||''));fs.writeFileSync(path.join(output,'results.log'),log);process.stdout.write(log);
if(result.status!==0||!/PASS: \d+ shell-action checks/.test(log))process.exitCode=result.status||1;
