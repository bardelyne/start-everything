import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'locales');
const files = fs.readdirSync(directory).filter(name => name.endsWith('.json'));
files.sort((a, b) => a === 'en.json' ? -1 : b === 'en.json' ? 1 : a.localeCompare(b, 'en'));
const packs = files.map(file => ({tag: file.slice(0, -5), ...JSON.parse(fs.readFileSync(path.join(directory, file), 'utf8'))}));
const keys = Object.keys(packs[0].strings);
const placeholders = text => [...text.matchAll(/\{(?:\d+|command)\}/g)].map(m => m[0]).sort().join('|');
for (const pack of packs) {
    if (Object.keys(pack.strings).length !== keys.length) throw Error(`${pack.tag}: wrong key count`);
    for (const key of keys) {
        const value = pack.strings[key];
        if (typeof value !== 'string' || !value.trim()) throw Error(`${pack.tag}: missing ${key}`);
        if (placeholders(value) !== placeholders(packs[0].strings[key])) throw Error(`${pack.tag}: placeholders in ${key}`);
        if (/[\u0000\u202a-\u202e\u2066-\u2069]/u.test(value)) throw Error(`${pack.tag}: control character in ${key}`);
    }
    if (new Intl.Locale(pack.tag).textInfo.direction !== 'ltr') throw Error(`${pack.tag}: RTL languages are excluded`);
}
// Orthographic joiners are valid in Telugu and other scripts. Spell them as
// escapes in C++ so Windhawk's invisible-whitespace validation stays clear.
const wide = text => 'L' + JSON.stringify(text).replace(/[\u200c\u200d]/gu, char =>
    '\\u' + char.charCodeAt(0).toString(16).padStart(4, '0'));
let code = `// Generated by scripts/embed-locales.mjs. Edit locales/*.json, then regenerate.
namespace i18n {
enum class Key {
${keys.map(key => `    ${key},`).join('\n')}
    Count
};
struct Locale {
    const wchar_t* tag;
    const wchar_t* text[static_cast<size_t>(Key::Count)];
};
inline constexpr Locale kLocales[] = {
${packs.map(pack => `    {${wide(pack.tag.toLowerCase())}, {\n${keys.map(key => `        ${wide(pack.strings[key])}, // ${key}`).join('\n')}\n    }},`).join('\n')}
};
inline std::atomic<const Locale*> g_locale{&kLocales[0]};

inline std::wstring NormalizeTag(std::wstring_view tag) {
    if (tag.size() >= LOCALE_NAME_MAX_LENGTH) return {};
    std::wstring normalized(tag);
    for (auto& c : normalized) {
        if (c == L'_') c = L'-';
        if (c >= L'A' && c <= L'Z') c += L'a' - L'A';
    }
    return normalized;
}

inline const Locale* Resolve(std::wstring_view requested) {
    std::wstring tag = NormalizeTag(requested);
    if (tag == L"zh" || tag == L"zh-cn" || tag == L"zh-sg" || tag == L"zh-chs") tag = L"zh-hans";
    if (tag == L"zh-tw" || tag == L"zh-hk" || tag == L"zh-mo" || tag == L"zh-cht") tag = L"zh-hant";
    if (tag == L"pt") tag = L"pt-pt";
    if (tag == L"no" || tag.starts_with(L"no-no")) tag = L"nb";
    if (tag == L"tl" || tag.starts_with(L"tl-")) tag = L"fil";
    while (!tag.empty()) {
        for (const auto& locale : kLocales) if (tag == locale.tag) return &locale;
        const size_t dash = tag.rfind(L'-');
        if (dash == std::wstring::npos) break;
        tag.resize(dash);
    }
    return &kLocales[0];
}

inline void Load(std::wstring_view requested) {
    const Locale* locale;
    if (requested.empty() || NormalizeTag(requested) == L"auto") {
        wchar_t name[LOCALE_NAME_MAX_LENGTH]{};
        const LCID id = MAKELCID(GetUserDefaultUILanguage(), SORT_DEFAULT);
        locale = LCIDToLocaleName(id, name, ARRAYSIZE(name), 0) ? Resolve(name) : &kLocales[0];
    } else {
        locale = Resolve(requested);
    }
    g_locale.store(locale, std::memory_order_release);
}

inline const wchar_t* Text(Key key) {
    return g_locale.load(std::memory_order_acquire)->text[static_cast<size_t>(key)];
}

inline const wchar_t* Tag() { return g_locale.load(std::memory_order_acquire)->tag; }

// Replace only placeholders from the template; user values are never reparsed.
inline std::wstring Format(Key key, std::initializer_list<std::wstring_view> arguments) {
    std::wstring_view pattern = Text(key);
    std::wstring result;
    result.reserve(pattern.size() + 32);
    for (size_t i = 0; i < pattern.size();) {
        if (i + 2 < pattern.size() && pattern[i] == L'{' && pattern[i + 2] == L'}' &&
            pattern[i + 1] >= L'0' && pattern[i + 1] <= L'9') {
            const size_t index = pattern[i + 1] - L'0';
            if (index < arguments.size()) {
                result.append(*(arguments.begin() + index));
                i += 3;
                continue;
            }
        }
        result.push_back(pattern[i++]);
    }
    return result;
}

// Only use this for mod-owned labels. Names, paths, Windows-provided text and
// internal category/ranking identifiers stay unchanged.
inline std::wstring Label(std::wstring_view english) {
    static constexpr struct { const wchar_t* english; Key key; } labels[] = {
${keys.map(key => ({key, value:packs[0].strings[key]})).concat([{key:'BaseRadix',value:'Base Radix'},{key:'Folder',value:'Folder'}]).sort((a,b)=>a.value<b.value?-1:a.value>b.value?1:0).map(({key,value})=>`        {${wide(value)}, Key::${key}},`).join('\n')}
    };
    size_t first = 0, last = ARRAYSIZE(labels);
    while (first < last) {
        const size_t middle = first + (last - first) / 2;
        const int order = english.compare(labels[middle].english);
        if (!order) return Text(labels[middle].key);
        if (order < 0) last = middle; else first = middle + 1;
    }
    return std::wstring(english);
}

inline std::wstring Subtitle(std::wstring_view text) {
    constexpr std::wstring_view prefix = L"Settings \\u2022 ";
    if (text.starts_with(prefix)) return std::wstring(Text(Key::Settings)) + L" \\u2022 " + std::wstring(text.substr(prefix.size()));
    return Label(text);
}
} // namespace i18n
`;

const file = path.join(root, 'start-everything.wh.cpp');
let source = fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
const begin = '// ==StartEverythingLocalization==';
const end = '// ==/StartEverythingLocalization==';
const block = begin + '\n' + code + end;
if (source.includes(begin)) {
    source = source.slice(0, source.indexOf(begin)) + block + source.slice(source.indexOf(end) + end.length);
} else {
    source = source.replace('inline HMODULE GetCurrentModuleHandle()', block + '\n\ninline HMODULE GetCurrentModuleHandle()');
}
const setting = `  - language: auto
    $name: Display Language
    $description: Language of the search window, menus, previews and utility messages. Auto follows the Windows display language; unsupported languages use English. Only left-to-right languages are supported. Windows-provided app and Settings names keep their Windows language.
    $options:
    - auto: Auto (Windows display language)
${packs.map(pack => `    - ${pack.tag}: ${JSON.stringify(pack.name)}`).join('\n')}
`;
const settingBegin = '  # ==DisplayLanguageOptions==';
const settingEnd = '  # ==/DisplayLanguageOptions==';
const settingBlock = settingBegin + '\n' + setting + settingEnd + '\n';
if (source.includes(settingBegin)) {
    source = source.slice(0, source.indexOf(settingBegin)) + settingBlock + source.slice(source.indexOf(settingEnd) + settingEnd.length + 1);
} else {
    source = source.replace('- appearance:\n', '- appearance:\n' + settingBlock);
}
if (process.argv.includes('--check')) {
    const current = fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
    if (source !== current) throw Error('Embedded localization or language options are stale');
} else {
    fs.writeFileSync(file, source);
}
console.log(`${packs.length} complete LTR language packs, ${keys.length} strings each; embedded catalog ${process.argv.includes('--check')?'verified':'updated'}.`);
